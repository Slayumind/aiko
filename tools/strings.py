"""Builds the table of every word Aiko says, for both cores, from one list of strings.

Run it from the repository root after editing tools/strings.json:

    python tools/strings.py

It writes src/Aiko.Core/Strings.cs and mac/Sources/AikoKit/Strings.swift. Both apps say the same
words because both are made from this one file; a table typed a second time by hand would drift
apart in a week. The words live in the cores, so the rules that choose them can be tested there.

The files go into the source tree rather than being generated during the build, because WPF
compiles XAML in a second pass through a temporary project that cannot see files the first pass
made. That failure looks like "the name Strings does not exist" and takes a while to understand.
"""

import io
import json
import re
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

CORE_HEAD = '''// <auto-generated>
//     Made by tools/strings.py from tools/strings.json. Do not edit by hand: run the script.
// </auto-generated>

#nullable enable

namespace Aiko.Core;

/// The two languages Aiko has words for. The setting also has "follow the system", which is
/// turned into one of these before the app asks for a word.
public enum StringLanguage
{
    English,
    Russian,
}

/// Every word Aiko says, in the language the user chose. One property per string, so a key that
/// does not exist is a build error and not a blank label somebody finds months later.
///
/// The table is the twin of Strings.swift in AikoKit.
public static class Strings
{
    private static volatile StringLanguage chosen = StringLanguage.English;

    /// Set at startup and again when the language changes. Volatile because the bridge and the app
    /// may ask from another thread, not because the value changes often.
    public static StringLanguage Language
    {
        get => chosen;
        set => chosen = value;
    }

    public static readonly IReadOnlyDictionary<string, (string English, string Russian)> Table =
        new Dictionary<string, (string English, string Russian)>
        {
'''


def cs_text(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_core(path, data):
    parts = [CORE_HEAD]
    for key, value, *_ in data:
        parts.append('            ["%s"] = ("%s", "%s"),\n' % (key, cs_text(value[0]), cs_text(value[1])))
    parts.append("        };\n\n")
    parts.append("    public static string Get(string key) =>\n"
                 "        Table.TryGetValue(key, out var pair) ? (Language == StringLanguage.Russian ? pair.Russian : pair.English) : key;\n")
    for key, value, *_ in data:
        summary = value[0].replace("\n", " ")
        if len(summary) > 92:
            summary = summary[:89] + "..."
        summary = summary.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        parts.append('\n    /// %s\n    public static string %s => Get("%s");\n' % (summary, key, key))
    parts.append("}\n")
    io.open(path, "w", encoding="utf-8", newline="\n").write("".join(parts))


SWIFT_HEAD = '''// Made by tools/strings.py from tools/strings.json. Do not edit by hand: run the script.

import Foundation

/// The two languages Aiko has words for. The setting also has "follow the system", which is
/// turned into one of these before the app asks for a word.
public enum StringLanguage: Sendable, Equatable {
    case english
    case russian
}

/// Every word Aiko says, in the language the user chose. One property per string, so a key that
/// does not exist is a build error and not a blank label somebody finds months later.
///
/// The table is the twin of Strings.cs in Aiko.Core on Windows.
public enum Strings {
    /// Set at startup and again when the language changes. The lock is there because the bridge
    /// and the app may ask from another thread, not because the value changes often.
    nonisolated(unsafe) private static var chosen = StringLanguage.english
    private static let lock = NSLock()

    public static var language: StringLanguage {
        get { lock.lock(); defer { lock.unlock() }; return chosen }
        set { lock.lock(); defer { lock.unlock() }; chosen = newValue }
    }

    public static func get(_ key: String) -> String {
        guard let pair = table[key] else { return key }
        return language == .russian ? pair.russian : pair.english
    }

    /// Fills {0}, {1} and so on, the way string.Format does on Windows. The texts are shared, so
    /// the placeholders have to be read the same way on both systems.
    public static func format(_ text: String, _ arguments: CustomStringConvertible...) -> String {
        var filled = text
        for (index, argument) in arguments.enumerated() {
            filled = filled.replacingOccurrences(of: "{\\(index)}", with: argument.description)
        }
        return filled
    }

    public static let table: [String: (english: String, russian: String)] = [
'''


def swift_name(key):
    name = key[0].lower() + key[1:]
    keywords = {
        "as", "associatedtype", "break", "case", "catch", "class", "continue", "default", "defer",
        "deinit", "do", "else", "enum", "extension", "fallthrough", "false", "fileprivate", "for",
        "func", "guard", "if", "import", "in", "init", "inout", "internal", "is", "let", "nil",
        "operator", "private", "protocol", "public", "repeat", "rethrows", "return", "self",
        "static", "struct", "subscript", "super", "switch", "throw", "throws", "true", "try",
        "typealias", "var", "where", "while",
    }
    return "`%s`" % name if name in keywords else name


def for_mac(entry):
    """The words of the Mac: its own where the entry has them (a place of Windows, such as
    Credential Manager, has another name there), the words of Windows otherwise."""
    return entry[2]["mac"] if len(entry) > 2 else entry[1]


def mac_keys(text):
    """Every Ctrl+ in the words is a key of Aiko itself, and on the Mac that key is Cmd (D-425)."""
    return text.replace("Ctrl+", "Cmd+")


def swift_text(text):
    return mac_keys(text).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def write_swift(path, data):
    parts = [SWIFT_HEAD]
    for entry in data:
        key, value = entry[0], for_mac(entry)
        parts.append('        "%s": ("%s", "%s"),\n'
                     % (key, swift_text(value[0]), swift_text(value[1])))
    parts.append("    ]\n")

    for entry in data:
        key, value = entry[0], for_mac(entry)
        summary = mac_keys(value[0]).replace("\n", " ")
        if len(summary) > 92:
            summary = summary[:89] + "..."
        # Spelled with the type name because a bare get( reads as the start of a getter.
        parts.append('\n    /// %s\n    public static var %s: String { Strings.get("%s") }\n'
                     % (summary, swift_name(key), key))
    parts.append("}\n")
    io.open(path, "w", encoding="utf-8", newline="\n").write("".join(parts))


def check(data):
    """What a rewrite breaks quietly. A missing key is a build error on both systems, but these
    three are not, and the last one cost a Russian window its numbers once."""
    keys = [entry[0] for entry in data]
    if len(keys) != len(set(keys)):
        raise SystemExit("two entries share a key")

    pairs = [(entry[0], entry[1]) for entry in data] + [(entry[0] + " on the Mac", entry[2]["mac"]) for entry in data if len(entry) > 2]
    for key, (english, russian) in pairs:
        if not english.strip() or not russian.strip():
            raise SystemExit("%s: one of the two languages is empty" % key)

        # {0} and {1} are filled in by the app. A language that lost one shows a number that
        # never arrives, or drops the one the sentence was built around.
        holes = lambda text: sorted(re.findall(r"\{\d+\}", text))
        if holes(english) != holes(russian):
            raise SystemExit("%s: %s in English, %s in Russian"
                             % (key, holes(english) or "no {0}", holes(russian) or "no {0}"))


def main():
    data = json.load(io.open(os.path.join(HERE, "strings.json"), encoding="utf-8"))
    check(data)

    write_core(os.path.join(ROOT, "src", "Aiko.Core", "Strings.cs"), data)
    write_swift(os.path.join(ROOT, "mac", "Sources", "AikoKit", "Strings.swift"), data)
    print("strings: %d" % len(data))


if __name__ == "__main__":
    main()
